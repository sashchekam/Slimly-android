package com.slimly.feature.debug.api

import com.slimly.navigation.Route
import kotlinx.parcelize.Parcelize

/**
 * Отладочное меню — единственный экран, до которого нельзя дойти
 * из интерфейса. Маршрут в роутер кладут только пять нажатий на строку
 * версии и метка DEBUG, и только в отладочной сборке: в релизной резолвер
 * не регистрируется и вести сюда нечему.
 *
 * Тряски, как на iOS, здесь нет: держать `SensorManager` ради сервисного
 * экрана не стоит.
 */
@Parcelize
enum class DebugRoute : Route {
    Menu,

    /** Значения удалённого конфига и локальные подмены к ним. */
    RemoteConfig,

    /** Журнал отправленной аналитики: события, их параметры и свойства. */
    Analytics,
}
