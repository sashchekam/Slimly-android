package com.slimly.core.service

import android.content.Intent
import android.net.Uri

/**
 * Готовый файл наружу: системная шторка «Поделиться» и переход
 * «Открыть в…».
 *
 * Намерение собирает `:mediakit`: право на чтение файла выдаёт его
 * `FileProvider`, и знает о нём только он. Экрану остаётся запустить
 * готовое намерение — запускать его умеет одна Activity, как и системный
 * запрос на удаление оригиналов.
 *
 * Это и есть та самая «шторка», которой на Android до сих пор не было:
 * смотреть и слушать по-настоящему человек идёт в системное приложение,
 * а не в наш просмотр.
 */
interface MediaFileSharing {
    /**
     * Шторка «Поделиться». Один файл уходит `ACTION_SEND`, несколько —
     * `ACTION_SEND_MULTIPLE`. `null` — делиться нечем.
     */
    fun shareIntent(files: List<Uri>): Intent?

    /**
     * Открыть файл системным приложением: PDF — просмотрщиком, дорожку —
     * плеером. `null` — открыть нечем: на устройстве нет ни одного
     * приложения, которое берёт такой файл.
     */
    fun viewIntent(file: Uri): Intent?
}
