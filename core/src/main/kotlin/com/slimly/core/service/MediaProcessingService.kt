package com.slimly.core.service

import android.graphics.Bitmap
import android.net.Uri
import com.slimly.core.model.DocumentQuad
import com.slimly.core.model.ProcessingEvent
import com.slimly.core.model.ProcessingHistory
import com.slimly.core.model.ProcessingOutcome
import com.slimly.core.model.ProcessingRequest
import com.slimly.core.model.ProcessingResult
import com.slimly.core.model.ProcessingRun
import com.slimly.core.model.ProcessingStats
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.StateFlow

/**
 * Обработка файлов и собственная база сделанного.
 *
 * База своя, потому что система не помнит, что мы делали с файлами: всё,
 * что показано в профиле, приложение записало о себе само.
 */
interface MediaProcessingService {
    suspend fun stats(): ProcessingStats

    /**
     * Журнал работ с датами — из него собирается разрез по инструментам
     * и по времени. Общая сумма на такой вопрос не отвечает: в ней нет
     * ни дат, ни того, каким инструментом это сделано.
     */
    suspend fun history(): ProcessingHistory

    /**
     * Работа, которая идёт прямо сейчас. `null` — сервис свободен.
     *
     * Смотрит сюда уведомление, а не экран: свернуть приложение посреди
     * обработки на Android — обычное дело, и убитая при этом работа читалась
     * бы как поломка.
     */
    val active: StateFlow<ProcessingRun?>

    /**
     * Поток событий обработки. В отличие от iOS, отмена подписки работу
     * не останавливает: уход с экрана — это ещё не отказ от неё. Работа живёт
     * в приложении, а поток только показывает, как она идёт; остановить её
     * можно только [cancel].
     *
     * Повторная подписка на то же задание не запускает его заново — она
     * подключается к уже идущему и сразу получает последнее событие.
     *
     * Готовые файлы остаются внутри приложения: наружу — в медиатеку или
     * «Файлы» — их выносит только [save].
     */
    fun process(request: ProcessingRequest): Flow<ProcessingEvent>

    /**
     * Остановить работу. Недописанные файлы убираются за собой: отмена
     * на середине не должна оставлять в кэше куски, которые ни показать,
     * ни сохранить.
     */
    fun cancel()

    /**
     * Разложить готовые файлы по месту.
     *
     * Отдельный шаг, а не хвост обработки: пока человек не нажал «сохранить»,
     * класть что-то в его галерею рано.
     *
     * Наружу уходит копия: рабочая папка остаётся на месте и после
     * сохранения — по ней показывают «после» в сравнении и ею делятся,
     * а адрес в галерее или в общей коллекции за пределами системного
     * приложения ничего не значит. Поэтому адреса в итоге те же.
     *
     * Файл, который сохранить не удалось, переезжает в список отказов —
     * один отказ не отменяет остальные.
     */
    suspend fun save(outcome: ProcessingOutcome): ProcessingOutcome

    /**
     * Поменять имя готовому файлу — пока он ещё лежит в рабочей папке.
     *
     * После сохранения имя правят снаружи: в «Файлах» его меняет системный
     * менеджер, а в медиатеке его и не видно. Возвращает тот же результат
     * с новым именем и новым адресом.
     */
    suspend fun rename(result: ProcessingResult, name: String): ProcessingResult
}

/**
 * Как долгой работе найти сервисы приложения.
 *
 * Системный сервис создаёт не composition root, а сама система, — параметров
 * в конструктор ему не передашь. Единственное, что у него есть, — это
 * `Application`, поэтому её и просим представиться.
 */
interface ProcessingHost {
    val processing: MediaProcessingService
}

/**
 * Кадр из готового файла.
 *
 * Результат обработки ещё не запись медиатеки — это просто файл на диске,
 * и достать из него картинку умеет только модуль системной обработки.
 * Экранам итога нужен один этот интерфейс, а не весь медиастек.
 *
 * Растр, а не байты, как на iOS: кодировать кадр в JPEG, чтобы экран тут же
 * разобрал его обратно, — работа впустую. Так же устроены и миниатюры
 * медиатеки, и кадры видоискателя.
 */
fun interface MediaPreviewRenderer {
    /**
     * Кадр готового файла, вписанный в [maxPixel] по длинной стороне.
     * `null` — показывать нечего: у дорожки кадра нет вовсе, а битый файл
     * не разбирается.
     */
    suspend fun preview(uri: Uri, maxPixel: Int): Bitmap?
}

/**
 * Поиск листа в готовом кадре.
 *
 * Отдельно от обработки: экран правки границ показывает рамку до того, как
 * что-то запущено, и просить ради этого собрать документ было бы странно.
 * Работает с кадром, а не с записью медиатеки, — искать границы нужно ровно
 * в том изображении, которое человек видит на экране: иначе рамка пообещает
 * одно, а обрежется другое.
 *
 * Растр, а не байты, как на iOS: и миниатюра медиатеки, и кадр видоискателя
 * приходят готовым `Bitmap`, и кодировать их в JPEG ради того, чтобы тут же
 * разобрать обратно, — работа впустую. Функция обычная, не приостанавливаемая:
 * поток кадров разбирается на своём исполнителе, а экран границ — в своей
 * корутине, и навязывать им обоим один способ уйти с главного потока незачем.
 */
fun interface DocumentBoundsDetector {
    /**
     * Границы листа в долях кадра от левого верхнего угла.
     * `null` — листа в кадре не видно, и предлагать нечего.
     */
    fun bounds(frame: Bitmap): DocumentQuad?
}
