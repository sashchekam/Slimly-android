package com.slimly.navigation

import android.os.Parcelable

/**
 * Маршрут — это значение, а не действие. Открыть экран = положить маршрут
 * в состояние роутера.
 *
 * Каждая фича объявляет свои маршруты в тонком `:api`-модуле: там нет UI,
 * поэтому импортировать его может кто угодно, не создавая зависимости
 * между фичами.
 *
 * `Parcelable`, потому что процесс убивают: стек роутера уезжает
 * в `savedInstanceState` и возвращается оттуда живым. Писать `writeToParcel`
 * руками не нужно — маршрут помечается `@Parcelize`.
 *
 * Стирания типа, как иосный `AnyRoute`, здесь нет и не нужно: `NavigationStack`
 * требовал один конкретный тип пути, а хост на Compose рисует список
 * `Route` как есть.
 */
interface Route : Parcelable
