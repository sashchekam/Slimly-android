package com.slimly.mediakit.scan

import com.slimly.core.model.ScanMode

/**
 * Разрешение готовой страницы — в точках на дюйм листа A4.
 *
 * Считаем от листа, а не от снимка: страница вписывается в A4, и «сколько
 * пикселей досталось букве» на печати определяет только это число.
 */
internal data class PageResolution(
    /**
     * Точек на дюйм. Настольный сканер по умолчанию работает на трёхстах,
     * и это не круглое число из воздуха: ниже засечки и тонкие штрихи
     * перестают попадать в пиксель целиком, а глаз читает это как
     * размазанный текст.
     */
    val dpi: Float,
    /**
     * Во сколько раз позволено растянуть снимок, если своих пикселей
     * не хватило. Больше единицы имеет смысл только перед порогом: новых
     * букв интерполяция не рисует, зато край буквы, посчитанный
     * по растянутому кадру, ложится ровнее.
     */
    val maxUpscale: Float,
) {
    /** Длинная сторона готовой страницы в пикселях. */
    val pageSide: Float
        get() = dpi * A4_LONG_SIDE

    private companion object {
        /** Длинная сторона A4 в дюймах: 842 pt при 72 pt на дюйм. */
        const val A4_LONG_SIDE = 842f / 72f
    }
}

/**
 * Как из полутонов страницы сделать чернила.
 *
 * Снимок отдаёт букву размытым пятном: ядро штриха тёмное, а вокруг него
 * широкая серая кайма. Глаз читает такую страницу как фотографию текста.
 * У скана распределение обратное — почти вся буква чёрная, серого только
 * тонкий край, — и кривая плотности как раз переводит одно в другое.
 */
internal data class InkCurve(
    /** Яркость бумаги: всё светлее становится чистым белым. */
    val paper: Float,
    /** Яркость чернил: всё темнее становится чистым чёрным. */
    val ink: Float,
    /**
     * Степень плотности. Меньше единицы — серая кайма штриха уходит
     * в чёрное; чем меньше, тем жирнее и контрастнее буква.
     */
    val gamma: Float,
)

/** В сером и ч/б цвета нет вовсе — страницу пишем одним каналом вместо трёх. */
internal val ScanMode.isMonochrome: Boolean
    get() = this != ScanMode.COLOR

internal val ScanMode.resolution: PageResolution
    get() = when (this) {
        // Полутоновая страница живёт в JPEG, и каждый лишний пиксель стоит
        // веса: триста — потолок, после которого растёт файл, а не чёткость.
        ScanMode.COLOR, ScanMode.GRAYSCALE -> PageResolution(dpi = 300f, maxUpscale = 1f)

        // Двухцветной странице разрешение достаётся почти даром — бит
        // на пиксель, дальше Flate. Порог же считается по соседям, поэтому
        // лишние пиксели здесь превращаются в ровный край буквы.
        ScanMode.BLACK_AND_WHITE -> PageResolution(dpi = 400f, maxUpscale = 1.5f)
    }

/**
 * Кривая чернил. У двухцветного режима её нет: там за плотность отвечает
 * [SauvolaBinarizer], и подсунутая ему заранее исправленная яркость только
 * сбила бы локальную статистику, по которой он считает порог.
 */
internal val ScanMode.inkCurve: InkCurve?
    get() = when (this) {
        // Цвету достаётся мягкая кривая: в этом режиме на странице ждут
        // печать, подпись и картинку, а не только текст, и упирать концы
        // шкалы в белое и чёрное значило бы срезать у них полутона.
        ScanMode.COLOR -> InkCurve(paper = 0.92f, ink = 0.08f, gamma = 0.7f)

        // Пороги сведены к середине шкалы, а показатель, наоборот, поднят:
        // вместе это даёт то же чёрное тело буквы, не выбивая светлые
        // полутона, которых у серого режима и так немного.
        ScanMode.GRAYSCALE -> InkCurve(paper = 0.88f, ink = 0.12f, gamma = 0.6f)

        ScanMode.BLACK_AND_WHITE -> null
    }

/**
 * Качество полутоновой страницы. Двухцветная в JPEG не попадает вовсе,
 * поэтому её здесь нет.
 *
 * Сильнее всего JPEG звенит на границе чёрной буквы и белого поля — то есть
 * ровно на содержании скана. Экономить здесь нельзя: разница между 70 и 90
 * на снимке кота незаметна, а на строчке текста видна сразу.
 */
internal val ScanMode.jpegQuality: Int
    get() = when (this) {
        ScanMode.COLOR -> 90
        ScanMode.GRAYSCALE, ScanMode.BLACK_AND_WHITE -> 92
    }
