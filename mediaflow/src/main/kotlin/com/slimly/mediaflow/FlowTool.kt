package com.slimly.mediaflow

/**
 * Инструмент, которому принадлежит шаг общего флоу.
 *
 * Экраны выбора, обработки и итога у инструментов одни и те же, поэтому
 * и события у них одни: различает их этот параметр. Так воронка описана
 * один раз, а разбивка по инструментам получается фильтром в отчёте.
 *
 * Конвертация разъехалась на два значения намеренно: фото и видео идут
 * одними экранами, но это разные привычки и разные деньги.
 */
enum class FlowTool(val value: String) {
    COMPRESS("compress"),
    CONVERT_PHOTO("convert_photo"),
    CONVERT_VIDEO("convert_video"),
    AUDIO("audio"),
    SCAN("scan"),
}
